BERKELEY_BLUE = "#003262"
BERKELEY_LIGHT_BLUE = "#3B7EA1"
CALIFORNIA_GOLD = "#FDB515"
BUG_RED = "#B7262E"
SOFT_RED = "#D96666"
SLATE = "#5B6F82"
FOG = "#E8EEF4"
CHARCOAL = "#1B2733"
GREEN = "#2A7F62"


def run_cmd(cmd: list[str]) -> str:
    return subprocess.check_output(cmd, text=True).strip()


def millions(values: pd.Series | np.ndarray) -> np.ndarray:
    return np.asarray(values, dtype=float) / 1_000_000.0


def format_float(value: float, digits: int = 2) -> str:
    return f"{value:.{digits}f}"


def get_git_date(commit: str) -> str:
    return run_cmd(["git", "show", "-s", "--format=%ad", "--date=short", commit])


def latest_series(history: pd.DataFrame, metric: str) -> tuple[np.ndarray, np.ndarray]:
    frame = history[["env_frames", metric]].dropna()
    return frame["env_frames"].to_numpy(dtype=float), frame[metric].to_numpy(dtype=float)


def load_track(task_yaml: Path) -> dict:
    with task_yaml.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def fetch_run(run_path: str):
    api = wandb.Api()
    run = api.run(run_path)
    history = run.history(samples=2000)
    return run, history


def phase_transition_frames(history: pd.DataFrame) -> dict[str, float]:
    phase = history[["env_frames", "curriculum/phase"]].dropna()
    if phase.empty:
        return {"phase1": math.nan, "phase2": math.nan}
    phase1 = phase.loc[phase["curriculum/phase"] >= 0.95, "env_frames"]
    phase2 = phase.loc[phase["curriculum/phase"] >= 1.95, "env_frames"]
    return {
        "phase1": float(phase1.iloc[0]) if not phase1.empty else math.nan,
        "phase2": float(phase2.iloc[0]) if not phase2.empty else math.nan,
    }


def save_numbers_tex(output_path: Path, summary: dict, transitions: dict[str, float]) -> None:
    lap_pct = 100.0 * float(summary["race/lap_completion_rate"])
    crash_pct = 100.0 * float(summary["crash/total_rate"])
    gate11 = float(summary["gates/gate_11_crosses"])
    lines = [
        "% Auto-generated by docs/generate_drone_race_progress_assets.py",
        "\\newcommand{\\EvidenceRunID}{\\texttt{dwn4jigo}}",
        "\\newcommand{\\EvidenceRunURL}{https://wandb.ai/ee106b/omnidrones/runs/dwn4jigo}",
        f"\\newcommand{{\\LapCompletionPct}}{{{lap_pct:.1f}\\%}}",
        f"\\newcommand{{\\GatesPerEpisode}}{{{float(summary['race/gates_passed_per_ep']):.2f}}}",
        f"\\newcommand{{\\LapTimeSeconds}}{{{float(summary['race/lap_time_sec']):.2f}\\,s}}",
        f"\\newcommand{{\\MeanSpeedMs}}{{{float(summary['race/mean_speed_ms']):.2f}\\,m/s}}",
        f"\\newcommand{{\\MaxSpeedMs}}{{{float(summary['race/max_speed_ms']):.2f}\\,m/s}}",
        f"\\newcommand{{\\CrashRatePct}}{{{crash_pct:.1f}\\%}}",
        f"\\newcommand{{\\EntropyCoef}}{{{float(summary['entropy/current_coef']):.5f}}}",
        f"\\newcommand{{\\CurriculumPhase}}{{{int(round(float(summary['curriculum/phase'])) )}}}",
        f"\\newcommand{{\\AccuracyEMA}}{{{float(summary['curriculum/accuracy_ema']):.3f}}}",
        f"\\newcommand{{\\GateElevenCrosses}}{{{gate11:.3f}}}",
        f"\\newcommand{{\\PhaseOneFramesM}}{{{transitions['phase1'] / 1_000_000.0:.1f}M}}",
        f"\\newcommand{{\\PhaseTwoFramesM}}{{{transitions['phase2'] / 1_000_000.0:.1f}M}}",
    ]
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def style_axis(ax, title: str, ylabel: str, xlabel: str = "Environment Frames (Millions)") -> None:
    ax.set_title(title, loc="left", fontsize=12, fontweight="bold", color=BERKELEY_BLUE)
    ax.set_xlabel(xlabel, fontsize=10)
    ax.set_ylabel(ylabel, fontsize=10)
    ax.grid(True, alpha=0.22, linewidth=0.8)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)


def plot_track_schematic(task_cfg: dict, output_path: Path) -> None:
    track_cfg = task_cfg["track_config"]
    gate_ids = sorted(track_cfg.keys(), key=lambda x: int(x))
    xs = [track_cfg[g]["pos"][0] for g in gate_ids]
    ys = [track_cfg[g]["pos"][1] for g in gate_ids]
    zs = [track_cfg[g]["pos"][2] for g in gate_ids]

    fig = plt.figure(figsize=(11.5, 6.5), constrained_layout=True)
    gs = fig.add_gridspec(1, 2, width_ratios=[1.9, 1.1])
    ax = fig.add_subplot(gs[0, 0])
    ax_side = fig.add_subplot(gs[0, 1])

    for i in range(len(gate_ids) - 1):
        ax.annotate(
            "",
            xy=(xs[i + 1], ys[i + 1]),
            xytext=(xs[i], ys[i]),
            arrowprops=dict(arrowstyle="->", lw=2.0, color=BERKELEY_LIGHT_BLUE, alpha=0.9),
        )

    elevated_ids = {7, 11}
    stack_partner_ids = {8, 12}
    for gid, x, y, z in zip(gate_ids, xs, ys, zs):
        color = BERKELEY_BLUE
        edge = "white"
        size = 220
        if int(gid) in elevated_ids:
            color = CALIFORNIA_GOLD
            edge = BERKELEY_BLUE
            size = 340
        elif int(gid) in stack_partner_ids:
            color = BERKELEY_LIGHT_BLUE
            edge = BERKELEY_BLUE
            size = 280
        if int(gid) == 13:
            color = BUG_RED
            size = 260
        ax.scatter(x, y, s=size, c=color, edgecolors=edge, linewidths=1.8, zorder=3)
        ax.text(x + 0.35, y + 0.35, f"G{gid}", fontsize=10, weight="bold", color=CHARCOAL)

    ax.plot([track_cfg["7"]["pos"][0], track_cfg["8"]["pos"][0]], [track_cfg["7"]["pos"][1], track_cfg["8"]["pos"][1]],
            linestyle="--", color=BUG_RED, linewidth=2, alpha=0.8)
    ax.plot([track_cfg["11"]["pos"][0], track_cfg["12"]["pos"][0]], [track_cfg["11"]["pos"][1], track_cfg["12"]["pos"][1]],
            linestyle="--", color=BUG_RED, linewidth=2, alpha=0.8)

    ax.set_facecolor("#FBFCFE")
    ax.set_title("Top-Down Race Layout from cfg/task/DroneRace.yaml", loc="left",
                 fontsize=13, fontweight="bold", color=BERKELEY_BLUE)
    ax.set_xlabel("X (m)")
    ax.set_ylabel("Y (m)")
    ax.grid(True, alpha=0.22)
    ax.set_aspect("equal", adjustable="box")

    ax_side.axis("off")
    ax_side.set_title("Key Geometry", loc="left", fontsize=13, fontweight="bold", color=BERKELEY_BLUE)
    bullet = (
        "• 13 YAML gate entries, with Gate 13 duplicating Gate 1 for lap closure\n"
        "• Elevated gates: G7 and G11 at z = 3.0 m\n"
        "• Stacked reversals: G7→G8 and G11→G12 share XY but flip height / facing\n"
        "• Hardest maneuvers are the elevated drop-back transitions and lap closure bookkeeping"
    )
    ax_side.text(0.0, 0.82, bullet, fontsize=11, va="top", color=CHARCOAL, linespacing=1.45)

    side_y = np.arange(len(gate_ids))
    ax_side_in = ax_side.inset_axes([0.05, 0.05, 0.9, 0.45])
    colors = [CALIFORNIA_GOLD if int(g) in elevated_ids else BERKELEY_LIGHT_BLUE for g in gate_ids]
    ax_side_in.barh(side_y, zs, color=colors, edgecolor=BERKELEY_BLUE, alpha=0.95)
    ax_side_in.set_yticks(side_y, [f"G{g}" for g in gate_ids], fontsize=8)
    ax_side_in.set_xlabel("Gate origin z (m)", fontsize=9)
    ax_side_in.set_title("Elevation profile", fontsize=10, color=BERKELEY_BLUE, loc="left")
    ax_side_in.grid(True, axis="x", alpha=0.18)
    ax_side_in.spines["top"].set_visible(False)
    ax_side_in.spines["right"].set_visible(False)

    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)



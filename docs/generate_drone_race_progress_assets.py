def generate_assets(run_path: str, task_yaml: Path, output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    run, history = fetch_run(run_path)
    task_cfg = load_track(task_yaml)
    summary = dict(run.summary)
    transitions = phase_transition_frames(history)

    plot_track_schematic(task_cfg, output_dir / "drone_race_progress_track_schematic.png")
    plot_pipeline(output_dir / "drone_race_progress_pipeline.png")
    plot_entropy_curriculum(history, transitions, output_dir / "drone_race_progress_entropy_curriculum.png")
    plot_results_trends(history, output_dir / "drone_race_progress_results_trends.png")
    plot_speed_crash(history, output_dir / "drone_race_progress_speed_crash.png")
    plot_reward_components(history, output_dir / "drone_race_progress_reward_components.png")
    plot_gate_crossings(summary, output_dir / "drone_race_progress_gate_crossings.png")
    plot_reset_curriculum(summary, output_dir / "drone_race_progress_reset_curriculum.png")
    plot_network_architecture(output_dir / "drone_race_progress_network_architecture.png")
    plot_bug_timeline(output_dir / "drone_race_progress_bug_timeline.png")
    save_numbers_tex(output_dir / "drone_race_progress_numbers.tex", summary, transitions)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-path", default="ee106b/omnidrones/dwn4jigo")
    parser.add_argument("--task-yaml", default="cfg/task/DroneRace.yaml")
    parser.add_argument("--output-dir", default="docs/figures")

    ax_pie = fig.add_subplot(gs[0, 0])
    ax_bar = fig.add_subplot(gs[0, 1])

    shares = [
        float(summary["curriculum/reset_from_gate0_rate"]),
        float(summary["curriculum/reset_from_prev_gate_rate"]),
        float(summary["curriculum/reset_from_random_rate"]),
    ]
    labels = ["Gate 0", "Previous gate", "Random gate"]
    pie_colors = [BERKELEY_BLUE, BERKELEY_LIGHT_BLUE, CALIFORNIA_GOLD]
    wedges, _texts, _autotexts = ax_pie.pie(
        shares,
        labels=labels,
        autopct=lambda p: f"{p:.0f}%",
        startangle=110,
        colors=pie_colors,
        wedgeprops=dict(width=0.52, edgecolor="white"),
        textprops=dict(color=CHARCOAL, fontsize=10),
    )
    ax_pie.set_title("Reset curriculum mix", loc="left", fontsize=13, fontweight="bold", color=BERKELEY_BLUE)

    gate_ids = np.arange(12)
    emas = [float(summary[f"curriculum/reset_gate_{i:02d}_pass_ema"]) for i in gate_ids]

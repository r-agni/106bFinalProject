def plot_entropy_curriculum(history: pd.DataFrame, transitions: dict[str, float], output_path: Path) -> None:
    fig, axes = plt.subplots(2, 1, figsize=(11.8, 7.6), sharex=True, constrained_layout=True)
    top = axes[0]
    bottom = axes[1]

    x, entropy = latest_series(history, "entropy/current_coef")
    top.plot(millions(x), entropy, color=BUG_RED, linewidth=2.2, label="entropy/current_coef")
    if "entropy/target_coef" in history.columns:
        xt, target = latest_series(history, "entropy/target_coef")
        top.plot(millions(xt), target, color=SOFT_RED, linewidth=1.5, linestyle="--", label="entropy/target_coef")
    style_axis(top, "Adaptive entropy schedule from dwn4jigo", "Entropy coefficient")
    top.legend(frameon=False, loc="upper right")

    if "curriculum/phase" in history.columns:
        xp, phase = latest_series(history, "curriculum/phase")
        bottom.step(millions(xp), phase, where="post", color=BERKELEY_BLUE, linewidth=2.0, label="curriculum/phase")
    if "curriculum/accuracy_ema" in history.columns:
        xa, acc = latest_series(history, "curriculum/accuracy_ema")
        bottom.plot(millions(xa), acc, color=CALIFORNIA_GOLD, linewidth=2.0, label="curriculum/accuracy_ema")
    if "race/lap_completion_rate" in history.columns:
        xl, lap = latest_series(history, "race/lap_completion_rate")
        bottom.plot(millions(xl), lap, color=GREEN, linewidth=1.8, label="race/lap_completion_rate")
    style_axis(bottom, "Curriculum state and accuracy signal", "Phase / rate")
    bottom.set_ylim(-0.05, 2.2)
    bottom.legend(frameon=False, ncol=3, loc="upper left")

    for ax in axes:
        for key, color in [("phase1", BERKELEY_LIGHT_BLUE), ("phase2", BERKELEY_BLUE)]:
            value = transitions.get(key)
            if value and not math.isnan(value):
                ax.axvline(value / 1_000_000.0, color=color, linestyle=":", linewidth=1.5, alpha=0.9)

    top.text(0.99, 0.03, "Phase 1 unlock and phase 2 speed-focus marked with dotted lines",
             transform=top.transAxes, ha="right", va="bottom", fontsize=9, color=SLATE)
    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def plot_results_trends(history: pd.DataFrame, output_path: Path) -> None:
    fig, axes = plt.subplots(2, 2, figsize=(12, 8), constrained_layout=True)
    metrics = [
        ("race/lap_completion_rate", "Lap completion rate", BERKELEY_BLUE),
        ("race/gates_passed_per_ep", "Gates passed / episode", CALIFORNIA_GOLD),
        ("race/mean_speed_ms", "Mean speed (m/s)", GREEN),
        ("reward/total_return", "Episode return", BUG_RED),
    ]
    for ax, (metric, title, color) in zip(axes.flat, metrics):
        x, y = latest_series(history, metric)
        ax.plot(millions(x), y, color=color, linewidth=2.2)
        style_axis(ax, title, title if "return" not in title.lower() else "Return")
    axes[0, 0].set_ylim(0.0, 0.85)
    fig.suptitle("Training trends from the evidence run", x=0.03, y=1.01,
                 ha="left", fontsize=15, fontweight="bold", color=BERKELEY_BLUE)
    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def plot_speed_crash(history: pd.DataFrame, output_path: Path) -> None:
    fig, axes = plt.subplots(2, 1, figsize=(11.8, 7.2), sharex=True, constrained_layout=True)

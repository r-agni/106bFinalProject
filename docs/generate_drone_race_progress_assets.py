def plot_reward_components(history: pd.DataFrame, output_path: Path) -> None:
    fig, axes = plt.subplots(2, 1, figsize=(11.8, 7.4), sharex=True, constrained_layout=True)
    top, bottom = axes
    component_specs = [
        ("reward/gates_cumul", BERKELEY_BLUE, "gates"),
        ("reward/speed_cumul", GREEN, "speed"),
        ("reward/stacked_bonus_cumul", CALIFORNIA_GOLD, "stacked bonus"),
        ("reward/penalties_cumul", BUG_RED, "penalties"),
    ]
    for metric, color, label in component_specs:
        if metric in history.columns:
            x, y = latest_series(history, metric)
            if label == "penalties":
                y = np.abs(y)
            top.plot(millions(x), y, color=color, linewidth=2.0, label=label)
    if "reward/total_return" in history.columns:
        x, total = latest_series(history, "reward/total_return")
        top.plot(millions(x), total, color=CHARCOAL, linewidth=2.2, linestyle="--", label="total return")
    style_axis(top, "Reward component magnitudes", "Cumulative reward")
    top.legend(frameon=False, ncol=5, loc="upper left")

    frac_specs = [
        ("reward/gates_fraction", BERKELEY_BLUE, "gates fraction"),
        ("reward/speed_fraction", GREEN, "speed fraction"),
        ("reward/stacked_fraction", CALIFORNIA_GOLD, "stacked fraction"),
    ]
    for metric, color, label in frac_specs:
        if metric in history.columns:
            x, y = latest_series(history, metric)
            bottom.plot(millions(x), y, color=color, linewidth=2.0, label=label)
    style_axis(bottom, "Reward balance over time", "Fraction of return")
    bottom.legend(frameon=False, ncol=3, loc="upper left")
    fig.savefig(output_path, dpi=220, bbox_inches="tight")
    plt.close(fig)



#!/usr/bin/env python3
"""Generate figures and summary macros for the DroneRace progress slide deck.

This script pulls the W&B run history for the evidence run, combines it with the
current DroneRace task YAML and local git metadata, and produces a reproducible
set of charts for the Beamer presentation in docs/drone_race_progress_slides.tex.
"""

from __future__ import annotations

import argparse
import math
import subprocess
from pathlib import Path

import matplotlib

matplotlib.use("Agg")

